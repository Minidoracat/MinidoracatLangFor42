function RadioDataFlx.getLocalizedChannelName(frequency, fallback)
    local entry = RadioDataFlx.CHANNEL_NAMES[tonumber(frequency)]
    if not entry then
        return fallback
    end

    if entry.key and getTextOrNull then
        local translated = getTextOrNull(entry.key)
        if translated then
            return translated
        end
    end

    return entry.fallback or fallback
end

local function isDedicatedServer()
    return isServer and isServer() and (not isClient or not isClient())
end

function RadioDataFlx.patchChannelNames()
    -- Dedicated server 不應把 channel list 改成中文；MP client 端 UI 會依頻率顯示中文名稱。
    -- 這可避免 server preset/channel name 被中文化後，再被原版 UI 以 byte-wise 截斷成亂碼。
    if isDedicatedServer() then
        return
    end

    if not ZomboidRadio or not ZomboidRadio.getInstance then
        return
    end

    local radio = ZomboidRadio.getInstance()
    if not radio or not radio.addChannelName then
        return
    end

    for frequency, entry in pairs(RadioDataFlx.CHANNEL_NAMES) do
        radio:addChannelName(RadioDataFlx.getLocalizedChannelName(frequency, entry.CH), frequency, entry.category, true)
    end
end

function RadioDataFlx.onRefreshChannelNames()
    -- MP client 會在連線後收到 server channel list，可能覆寫本地名稱；前幾分鐘低頻重套即可。
    RadioDataFlx.patchChannelNames()
    RadioDataFlx._channelPatchTicks = RadioDataFlx._channelPatchTicks + 1
    if RadioDataFlx._channelPatchTicks >= 5 and Events.EveryOneMinute then
        Events.EveryOneMinute.Remove(RadioDataFlx.onRefreshChannelNames)
    end
end

if Events.OnGameStart then
    Events.OnGameStart.Add(RadioDataFlx.patchChannelNames)
end
if Events.OnConnected then
    Events.OnConnected.Add(RadioDataFlx.onRefreshChannelNames)
end
if Events.EveryOneMinute then
    Events.EveryOneMinute.Add(RadioDataFlx.onRefreshChannelNames)
end
